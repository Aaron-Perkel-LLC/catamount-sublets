import { sql } from "drizzle-orm";
import {
  boolean,
  char,
  check,
  doublePrecision,
  index,
  integer,
  numeric,
  pgTable,
  primaryKey,
  smallint,
  text,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import { LIMITS } from "@/config/site";
import {
  LISTING_STATUS_VALUES,
  ROOMMATE_GENDER_VALUES,
  ROOMMATE_PREFERENCE_VALUES,
  UTILITY_VALUES,
} from "@/lib/options";
import { user } from "./auth";
import { createdAt, inList, nullableTimestamp, num, updatedAt } from "./helpers";
import { semesters } from "./semesters";

/**
 * One listing per account (user_id is unique). Ids are preserved from the
 * legacy app, so they are GENERATED BY DEFAULT, not ALWAYS.
 *
 * No cover columns: the cover is the first photo by (sort_order, id). No
 * "first semester" column: listing_semesters.position = 0 is the first.
 */
export const listings = pgTable(
  "listings",
  {
    id: integer().primaryKey().generatedByDefaultAsIdentity(),
    userId: uuid()
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    price: numeric({ precision: 10, scale: 2, mode: "number" }).notNull(),
    priceNegotiable: boolean().notNull().default(false),
    address: text().notNull(),
    lat: doublePrecision().notNull(),
    lon: doublePrecision().notNull(),
    bedrooms: smallint(),
    bathrooms: numeric({ precision: 3, scale: 1, mode: "number" }),
    roommates: smallint(),
    roommateGender: text().notNull().default(""),
    roommatePreference: text().notNull().default(""),
    description: text(),
    /** The public name on the listing; blank shows the account's email local part. */
    displayName: text().notNull().default(""),
    contactEmail: text(),
    contactPhone: text(),
    utilityElectric: text().notNull().default(""),
    utilityGas: text().notNull().default(""),
    utilityWater: text().notNull().default(""),
    utilityInternet: text().notNull().default(""),
    utilityCost: numeric({ precision: 8, scale: 2, mode: "number" }),
    amenityFreeParking: boolean().notNull().default(false),
    amenityPaidParking: boolean().notNull().default(false),
    amenityLaundryFree: boolean().notNull().default(false),
    amenityLaundryPaid: boolean().notNull().default(false),
    amenityDishwasher: boolean().notNull().default(false),
    amenityAirConditioning: boolean().notNull().default(false),
    amenityPetsAllowed: boolean().notNull().default(false),
    amenityFurnished: boolean().notNull().default(false),
    status: text().notNull().default("open"),
    statusChangedAt: nullableTimestamp(),
    /** The share token the legacy site issued, so links already sent keep working. */
    legacyShareToken: char({ length: 10 }),
    /** Set by the migration script; lets --prune tell migrated rows from new ones. */
    legacyImport: boolean().notNull().default(false),
    postedAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique("listings_user_id_key").on(t.userId),
    index("listings_status_idx").on(t.status),
    check("listings_price_check", sql`${t.price} >= 0 and ${t.price} <= ${num(LIMITS.priceMax)}`),
    check("listings_address_check", sql`length(${t.address}) <= ${num(LIMITS.addressMaxChars)}`),
    check("listings_lat_check", sql`${t.lat} between -90 and 90`),
    check("listings_lon_check", sql`${t.lon} between -180 and 180`),
    check("listings_bedrooms_check", sql`${t.bedrooms} between 0 and 20`),
    check("listings_bathrooms_check", sql`${t.bathrooms} between 0.5 and 9.5`),
    check("listings_roommates_check", sql`${t.roommates} between 0 and 20`),
    check("listings_roommate_gender_check", inList(t.roommateGender, ROOMMATE_GENDER_VALUES)),
    check("listings_roommate_preference_check", inList(t.roommatePreference, ROOMMATE_PREFERENCE_VALUES)),
    check("listings_description_check", sql`length(${t.description}) <= ${num(LIMITS.descriptionMaxChars)}`),
    check("listings_display_name_check", sql`length(${t.displayName}) <= ${num(LIMITS.displayNameMaxChars)}`),
    check("listings_utility_electric_check", inList(t.utilityElectric, UTILITY_VALUES)),
    check("listings_utility_gas_check", inList(t.utilityGas, UTILITY_VALUES)),
    check("listings_utility_water_check", inList(t.utilityWater, UTILITY_VALUES)),
    check("listings_utility_internet_check", inList(t.utilityInternet, UTILITY_VALUES)),
    check("listings_utility_cost_check", sql`${t.utilityCost} >= 0`),
    check("listings_status_check", inList(t.status, LISTING_STATUS_VALUES)),
  ],
);

/**
 * The semesters a listing runs for, one row each, numbered in calendar order
 * (position 0 is the first). Written only by setListingSemesters().
 */
export const listingSemesters = pgTable(
  "listing_semesters",
  {
    listingId: integer()
      .notNull()
      .references(() => listings.id, { onDelete: "cascade" }),
    semesterCode: text()
      .notNull()
      .references(() => semesters.code, { onDelete: "restrict" }),
    position: smallint().notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.listingId, t.semesterCode] }),
    unique("listing_semesters_position_key").on(t.listingId, t.position),
    index("listing_semesters_semester_code_idx").on(t.semesterCode),
  ],
);

/**
 * A photo and its three derived images, all in the public media store under
 * the 32-hex `stem`. Files are never rewritten in place, so the URLs are
 * immutable. (listing_id, sort_order) is deliberately not unique: reordering
 * renumbers in a transaction, and reads order by (sort_order, id).
 */
export const listingPhotos = pgTable(
  "listing_photos",
  {
    id: integer().primaryKey().generatedByDefaultAsIdentity(),
    listingId: integer()
      .notNull()
      .references(() => listings.id, { onDelete: "cascade" }),
    sortOrder: integer().notNull(),
    stem: char({ length: 32 }).notNull().unique("listing_photos_stem_key"),
    displayUrl: text().notNull(),
    thumbUrl: text().notNull(),
    cardUrl: text().notNull(),
    width: integer(),
    height: integer(),
    bytes: integer(),
    contentType: text(),
    sha256: char({ length: 64 }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [index("listing_photos_listing_idx").on(t.listingId, t.sortOrder, t.id)],
);
